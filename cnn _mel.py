        mel = librosa.feature.melspectrogram(
            y=audio,
            sr=sr,
            n_fft=N_FFT,
            hop_length=HOP_LENGTH,
            n_mels=n_mels
        )

        mel_db = librosa.power_to_db(mel, ref=np.max).astype(np.float32)

        # time_only 使用：保留 n_mels 頻率高度，只調整時間軸
        mel_time_only = cv2.resize(
            mel_db,
            (IMAGE_SIZE, n_mels),
            interpolation=cv2.INTER_AREA
        )

        # baseline / improved 使用：統一調整為 128 × 128
        mel_resized = cv2.resize(
            mel_db,
            (IMAGE_SIZE, IMAGE_SIZE),
            interpolation=cv2.INTER_AREA
        )

        mel_features[n_mels].append(mel_time_only)
        resized_features[n_mels].append(mel_resized)

