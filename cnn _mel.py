import numpy as np
import tensorflow as tf
import random


def set_random_seed(seed):
    random.seed(seed)
    np.random.seed(seed)
    tf.keras.utils.set_random_seed(seed)


def prepare_features(features, train_idx, mode):
    """依模式準備特徵；標準化參數只由訓練集計算。"""
    X = features.astype(np.float32).copy()
    mean = None
    std = None

    if mode == "improved":
        mean = X[train_idx].mean()
        std = X[train_idx].std()
        std = max(float(std), 1e-6)
        X = (X - mean) / std

    return X[..., np.newaxis], mean, std


def evaluate_song_level(probabilities, indices, metadata):
    """平均同一首歌曲所有片段的預測機率，再計算歌曲準確率。"""
    rows = metadata.iloc[indices].reset_index(drop=True).copy()
    rows["true_label"] = rows["label"].astype(int).to_numpy()
    rows["p0"] = probabilities[:, 0]
    rows["p1"] = probabilities[:, 1]
    rows["p2"] = probabilities[:, 2]

    song_probs = rows.groupby("track_id")[
        ["p0", "p1", "p2"]
    ].mean()

    song_labels = rows.groupby("track_id")["true_label"].first()
    song_predictions = song_probs.to_numpy().argmax(axis=1)

    return accuracy_score(song_labels, song_predictions)


def train_and_evaluate(n_mels, mode, seed):
    """訓練單一模型，回傳片段與歌曲層級準確率。"""
    set_random_seed(seed)

    train_idx = split_indices["train"]
    val_idx = split_indices["val"]
    test_idx = split_indices["test"]

    if mode == "time_only":
        features = mel_features[n_mels]
    else:
        features = resized_features[n_mels]

    X, mean, std = prepare_features(features, train_idx, mode)
    y = audio_df["label"].to_numpy(dtype=np.int64)

    input_shape = X.shape[1:]
    model = build_cnn(input_shape, mode=mode)

    callbacks = []
    if mode == "improved":
        callbacks.append(
            EarlyStopping(
                monitor="val_loss",
                patience=5,
                restore_best_weights=True
            )
        )

    history = model.fit(
        X[train_idx],
        y[train_idx],
        validation_data=(X[val_idx], y[val_idx]),
        epochs=30,
        batch_size=8,
        callbacks=callbacks,
        verbose=0
    )

    test_probabilities = model.predict(
        X[test_idx],
        verbose=0
    )

    segment_accuracy = accuracy_score(
        y[test_idx],
        test_probabilities.argmax(axis=1)
    )

    song_accuracy = evaluate_song_level(
        test_probabilities,
        test_idx,
        audio_df
    )

    result = {
        "mode": mode,
        "n_mels": n_mels,
        "seed": seed,
        "epochs_trained": len(history.history["loss"]),
        "segment_accuracy": segment_accuracy,
        "song_accuracy": song_accuracy,
        "best_val_accuracy": max(history.history["val_accuracy"]),
    }

    del model
    tf.keras.backend.clear_session()

    return result

