# ------------------------------------------------------------------ 資料
def load_dataset(work_dir):
    """下載 Feanix/gtzan-10-sec，並依檔名取得 track_id（與原程式相同）。"""
    import tarfile
    from huggingface_hub import hf_hub_download
    archive = hf_hub_download(repo_id="Feanix/gtzan-10-sec", filename="data/genres.tar.gz",
                              repo_type="dataset")
    extract = Path(work_dir) / "gtzan_data"
    genres_dir = extract / "genres"
    if not genres_dir.is_dir():
        extract.mkdir(parents=True, exist_ok=True)
        with tarfile.open(archive, "r:gz") as tar:
            tar.extractall(extract)
    rows = []
    for g in GENRES:
        for f in sorted((genres_dir / g).glob("*.wav")):
            m = re.match(rf"{g}\.(\d+)_([123])\.wav$", f.name)
            if m:
                rows.append(dict(path=str(f), genre=g, track_id=f"{g}.{m.group(1)}",
                                 segment=int(m.group(2))))
    return pd.DataFrame(rows)


def make_split(df, split_seed):
    """與原程式相同：StratifiedGroupKFold(5) 取一折為 Test，再 (4) 取一折為 Validation。"""
    s1 = StratifiedGroupKFold(n_splits=5, shuffle=True, random_state=split_seed)
    tv_idx, te_idx = next(s1.split(df, y=df["genre"], groups=df["track_id"]))
    tv, te = df.iloc[tv_idx], df.iloc[te_idx]
    s2 = StratifiedGroupKFold(n_splits=4, shuffle=True, random_state=split_seed)
    tr_idx, va_idx = next(s2.split(tv, y=tv["genre"], groups=tv["track_id"]))
    tr, va = tv.iloc[tr_idx], tv.iloc[va_idx]
    assert set(tr.track_id).isdisjoint(va.track_id)
    assert set(tr.track_id).isdisjoint(te.track_id)
    assert set(va.track_id).isdisjoint(te.track_id)
    return tr.index.to_numpy(), va.index.to_numpy(), te.index.to_numpy()


def build_features(df, n_mels_list, modes, cache_path):
    """回傳 dict[(n_mels, mode)] -> float32 陣列 (N, H, W, 1)。音訊只讀一次。"""
    import librosa
    import cv2
    if cache_path and os.path.exists(cache_path):
        z = np.load(cache_path, allow_pickle=True)
        feats = {tuple(k.split("_", 1)): z[k] for k in z.files}
        feats = {(int(a), b): v for (a, b), v in feats.items()}
        if all((n, m) in feats for n in n_mels_list for m in modes):
            print("已讀取特徵快取：", cache_path)
            return feats
    buckets = {(n, m): [] for n in n_mels_list for m in modes}
    for i, path in enumerate(df["path"]):
        y, sr = librosa.load(path, sr=SR, mono=True)
        for n in n_mels_list:
            mel = librosa.feature.melspectrogram(y=y, sr=sr, n_fft=N_FFT, hop_length=HOP, n_mels=n)
            mel_db = librosa.power_to_db(mel, ref=np.max)
            for m in modes:
                size = (IMG, IMG) if m == "resize" else (IMG, n)   # cv2 的 dsize 為 (寬, 高)
                img = cv2.resize(mel_db, size, interpolation=cv2.INTER_AREA)
                buckets[(n, m)].append(img.astype(np.float32)[..., None])
        if (i + 1) % 100 == 0:
            print(f"  特徵擷取 {i + 1}/{len(df)}")
    feats = {k: np.stack(v) for k, v in buckets.items()}
    if cache_path:
        np.savez_compressed(cache_path, **{f"{n}_{m}": v for (n, m), v in feats.items()})
    return feats


# ------------------------------------------------------------------ 模型
def train_tf(recipe, Xtr, ytr, Xva, yva, Xte, seed, deterministic=False):
    import tensorflow as tf
    from tensorflow import keras
    from tensorflow.keras import layers
    cfg = RECIPES[recipe]
    keras.backend.clear_session()
    keras.utils.set_random_seed(seed)
    if deterministic:
        tf.config.experimental.enable_op_determinism()

    if cfg["norm"]:                       # 只用訓練集計算平均與標準差
        mu, sd = Xtr.mean(), Xtr.std() + 1e-6
        Xtr, Xva, Xte = (Xtr - mu) / sd, (Xva - mu) / sd, (Xte - mu) / sd

    x_in = keras.Input(shape=Xtr.shape[1:])
    x = x_in
    for filters in (32, 64, 128):
        x = layers.Conv2D(filters, (3, 3), activation="relu")(x)
        x = layers.MaxPooling2D((2, 2))(x)
    x = layers.GlobalAveragePooling2D()(x) if cfg["head"] == "gap" else layers.Flatten()(x)
    x = layers.Dense(128, activation="relu")(x)
    if cfg["dropout"] > 0:
        x = layers.Dropout(cfg["dropout"])(x)
    out = layers.Dense(3, activation="softmax")(x)
    model = keras.Model(x_in, out)
    model.compile(optimizer=keras.optimizers.Adam(), loss="sparse_categorical_crossentropy",
                  metrics=["accuracy"])

    callbacks = []
    if cfg["early"]:
        callbacks.append(keras.callbacks.EarlyStopping(monitor="val_loss", patience=5,
                                                       restore_best_weights=True))
    hist = model.fit(Xtr, ytr, validation_data=(Xva, yva), epochs=cfg["epochs"],
                     batch_size=BATCH, shuffle=True, verbose=0, callbacks=callbacks)
    probs = model.predict(Xte, batch_size=BATCH, verbose=0)
    h = pd.DataFrame(hist.history)
    best_epoch = int(np.argmin(h["val_loss"])) + 1
    return probs, h, best_epoch


def train_sklearn(recipe, Xtr, ytr, Xva, yva, Xte, seed, deterministic=False):
    """--selftest 用：不需要 TensorFlow，只用來測試彙整與統計流程。"""
    from sklearn.linear_model import LogisticRegression
    f = lambda X: X.reshape(len(X), -1)[:, ::50]
    clf = LogisticRegression(max_iter=300, random_state=seed).fit(f(Xtr), ytr)
    h = pd.DataFrame({"loss": [0.0], "val_loss": [0.0]})
    return clf.predict_proba(f(Xte)), h, 1


# ------------------------------------------------------------------ 評估
def evaluate(probs, y_te, track_te):
    clip_pred = probs.argmax(1)
    clip_acc = float((clip_pred == y_te).mean() * 100)
    loss = float(log_loss(y_te, probs, labels=[0, 1, 2]))
    pdf = pd.DataFrame(probs, columns=["p0", "p1", "p2"])
    pdf["track"], pdf["y"] = track_te, y_te
    song = pdf.groupby("track").agg(p0=("p0", "mean"), p1=("p1", "mean"), p2=("p2", "mean"),
                                    y=("y", "first"))
    sp = song[["p0", "p1", "p2"]].to_numpy().argmax(1)
    sy = song["y"].to_numpy()
    song_acc = float((sp == sy).mean() * 100)
    cm = confusion_matrix(sy, sp, labels=[0, 1, 2])
    recall = [float(cm[i, i] / cm[i].sum() * 100) if cm[i].sum() else np.nan for i in range(3)]
    return dict(clip_acc=clip_acc, song_acc=song_acc, test_loss=loss, n_songs=len(sy),
                recall_classical=recall[0], recall_hiphop=recall[1], recall_rock=recall[2]), cm


def t_ci(v, level=0.95):
    v = np.asarray(v, float)
    if len(v) < 2:
        return (np.nan, np.nan)
    h = stats.sem(v) * stats.t.ppf((1 + level) / 2, len(v) - 1)
    return (v.mean() - h, v.mean() + h)


def snr_larger_better(v):
    v = np.asarray(v, float)
    return float(-10 * np.log10(np.mean(1.0 / np.maximum(v, 1e-9) ** 2)))


def analyze(runs, out_dir, cms):
    lines = []
    P = lines.append
    # ---- 摘要表
    rows = []
    for (rec, mode, n), g in runs.groupby(["recipe", "mode", "n_mels"]):
        row = dict(recipe=rec, mode=mode, n_mels=n, runs=len(g))
        for col in ("song_acc", "clip_acc", "test_loss"):
            lo, hi = t_ci(g[col])
            row.update({f"{col}_mean": g[col].mean(), f"{col}_sd": g[col].std(ddof=1),
                        f"{col}_ci_low": lo, f"{col}_ci_high": hi})
        row["song_acc_min"] = g["song_acc"].min()
        row["song_acc_SN"] = snr_larger_better(g["song_acc"])
        rows.append(row)
    summ = pd.DataFrame(rows)
    summ.round(3).to_csv(os.path.join(out_dir, "summary_by_condition.csv"), index=False,
                         encoding="utf-8-sig")
    P("===== 各條件摘要（歌曲層級準確率 %）=====")
    P(summ[["recipe", "mode", "n_mels", "runs", "song_acc_mean", "song_acc_sd",
            "song_acc_ci_low", "song_acc_ci_high", "song_acc_min", "song_acc_SN",
            "clip_acc_mean", "test_loss_mean"]].round(2).to_string(index=False))

    # ---- 每個 (recipe, mode) 內比較 n_mels
    P("\n===== n_mels 之間的檢定（以 split_seed+seed 為配對單位）=====")
    for (rec, mode), g in runs.groupby(["recipe", "mode"]):
        wide = g.pivot_table(index=["split_seed", "seed"], columns="n_mels", values="song_acc")
        cols = list(wide.columns)
        P(f"\n[{rec} / {mode}]  重複數 = {len(wide)}")
        if len(wide) >= 3 and len(cols) >= 2:
            f, p = stats.f_oneway(*[wide[c].dropna() for c in cols])
            P(f"  單因子 ANOVA：F={f:.3f}, p={p:.4f}")
            lev = stats.levene(*[wide[c].dropna() for c in cols], center="median")
            P(f"  Levene（變異數是否相等）：p={lev.pvalue:.4f}")
            for a, b in itertools.combinations(cols, 2):
                d = (wide[b] - wide[a]).dropna()
                tt = stats.ttest_rel(wide[b].loc[d.index], wide[a].loc[d.index])
                try:
                    wp = stats.wilcoxon(d).pvalue if (d != 0).any() else 1.0
                except ValueError:
                    wp = np.nan
                P(f"  {b} vs {a}：平均差 {d.mean():+.2f} 個百分點, 配對 t p={tt.pvalue:.4f}, "
                  f"Wilcoxon p={wp:.4f}")
            P("  （比較次數較多時，請注意多重比較；可用 Bonferroni：p 乘以比較次數）")

    # ---- recipe / mode 的影響
    for factor, levels in (("recipe", ["orig", "improved"]), ("mode", ["resize", "time_only"])):
        if all(l in runs[factor].unique() for l in levels):
            P(f"\n===== {factor} 的影響（同 n_mels、同 seed 配對）=====")
            others = [c for c in ("recipe", "mode") if c != factor]
            for key, g in runs.groupby(others + ["n_mels"]):
                wide = g.pivot_table(index=["split_seed", "seed"], columns=factor, values="song_acc")
                if all(l in wide.columns for l in levels) and len(wide) >= 3:
                    d = (wide[levels[1]] - wide[levels[0]]).dropna()
                    tt = stats.ttest_rel(wide[levels[1]].loc[d.index], wide[levels[0]].loc[d.index])
                    P(f"  {key}: {levels[1]} - {levels[0]} = {d.mean():+.2f}, 配對 t p={tt.pvalue:.4f}")

    # ---- 兩因子 ANOVA（若有 statsmodels）
    try:
        import statsmodels.formula.api as smf
        import statsmodels.api as sm
        for rec, g in runs.groupby("recipe"):
            if g["mode"].nunique() > 1 and g["n_mels"].nunique() > 1:
                m = smf.ols("song_acc ~ C(n_mels) * C(mode)", data=g).fit()
                P(f"\n===== 兩因子 ANOVA（recipe={rec}）：n_mels × mode =====")
                P(sm.stats.anova_lm(m, typ=2).round(4).to_string())
    except Exception as e:           # 沒安裝 statsmodels 就略過
        P(f"\n（略過兩因子 ANOVA：{type(e).__name__}）")

    # ---- 各曲風召回率
    rc = runs.groupby(["recipe", "mode", "n_mels"])[
        ["recall_classical", "recall_hiphop", "recall_rock"]].agg(["mean", "std"]).round(2)
    rc.to_csv(os.path.join(out_dir, "per_class_recall.csv"), encoding="utf-8-sig")
    P("\n===== 各曲風歌曲層級召回率（平均、標準差，%）=====")
    P(rc.to_string())

    # ---- 混淆矩陣加總
    P("\n===== 歌曲層級混淆矩陣（所有重複加總；列=實際，欄=預測）=====")
    for key, cm in cms.items():
        name = "_".join(map(str, key))
        pd.DataFrame(cm, index=GENRES, columns=GENRES).to_csv(
            os.path.join(out_dir, f"confusion_sum_{name}.csv"), encoding="utf-8-sig")
        P(f"\n{key}\n" + pd.DataFrame(cm, index=GENRES, columns=GENRES).to_string())

    text = "\n".join(lines)
    with open(os.path.join(out_dir, "stats_report.txt"), "w", encoding="utf-8") as f:
        f.write(text)
    print(text)


def plot_runs(runs, out_dir):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    groups = list(runs.groupby(["recipe", "mode"]))
    fig, axes = plt.subplots(1, len(groups), figsize=(4.2 * len(groups), 4.2), sharey=True,
                             squeeze=False)
    rng = np.random.default_rng(0)
    for ax, ((rec, mode), g) in zip(axes[0], groups):
        ns = sorted(g["n_mels"].unique())
        for i, n in enumerate(ns):
            v = g.loc[g.n_mels == n, "song_acc"].to_numpy()
            ax.scatter(i + rng.uniform(-0.12, 0.12, len(v)), v, alpha=0.7, s=18)
            ax.errorbar(i + 0.25, v.mean(), yerr=v.std(ddof=1) if len(v) > 1 else 0,
                        fmt="o", color="black", capsize=4)
        ax.set_xticks(range(len(ns)))
        ax.set_xticklabels(ns)
        ax.set_title(f"{rec} / {mode}")
        ax.set_xlabel("n_mels")
        ax.grid(alpha=0.3)
    axes[0][0].set_ylabel("Song-level accuracy (%)")
    axes[0][0].set_ylim(50, 100)
    fig.suptitle("Each dot = one run; black = mean ± SD")
    fig.tight_layout()
    fig.savefig(os.path.join(out_dir, "song_accuracy_by_condition.png"), dpi=200)


